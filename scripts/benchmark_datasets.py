"""Actual large-file check; Python allocations and process peak working set are distinct metrics."""
import ctypes
import json
import os
import time
import tracemalloc
from uuid import uuid4

import bootstrap
from rainforge_datasets import DatasetEngine
from rainforge_recovery import atomic_json

root = bootstrap.ROOT / 'work/dataset-benchmark' / uuid4().hex
root.mkdir(parents=True)
source = root / 'large.jsonl'
with source.open('w', encoding='utf-8', newline='\n') as stream:
    for index in range(10000):
        stream.write(json.dumps({'index': index, 'text': 'dataset sample ' * 550}) + '\n')
engine = DatasetEngine(root)
started = time.monotonic()
tracemalloc.start()
key = engine.start(str(source), 'CC0-1.0', 'Synthetic benchmark generated by RainForge')['id']
engine.thread.join(timeout=120)
assert not engine.thread.is_alive(), 'Benchmark timed out'
_, peak = tracemalloc.get_traced_memory()
tracemalloc.stop()
run = next(r for r in engine.listing()['runs'] if r['id'] == key)
assert run['status'] == 'COMPLETED', run['error']
assert run['stats']['kept'] == 10000
assert peak < 16 * 1024 ** 2, f'Unexpected Python allocation peak: {peak}'
report = {'status': 'PASS', 'records': 10000, 'source_bytes': source.stat().st_size,
          'python_allocation_peak_bytes': peak, 'elapsed_seconds': round(time.monotonic()-started, 3),
          'stats': run['stats'], 'note': 'tracemalloc excludes native/SQLite buffers; process working set measured separately'}
if os.name == 'nt':
    class Counters(ctypes.Structure):
        _fields_ = [('cb', ctypes.c_ulong), ('PageFaultCount', ctypes.c_ulong),
                    *[(name, ctypes.c_size_t) for name in ('PeakWorkingSetSize', 'WorkingSetSize', 'QuotaPeakPagedPoolUsage',
                     'QuotaPagedPoolUsage', 'QuotaPeakNonPagedPoolUsage', 'QuotaNonPagedPoolUsage', 'PagefileUsage', 'PeakPagefileUsage')]]
    counter = Counters()
    counter.cb = ctypes.sizeof(counter)
    current = ctypes.windll.kernel32.GetCurrentProcess
    current.restype = ctypes.c_void_p
    get_memory = ctypes.windll.psapi.GetProcessMemoryInfo
    get_memory.argtypes = [ctypes.c_void_p, ctypes.POINTER(Counters), ctypes.c_ulong]
    if get_memory(current(), ctypes.byref(counter), counter.cb):
        report['process_peak_working_set_bytes'] = counter.PeakWorkingSetSize
atomic_json(bootstrap.ROOT / 'work/dataset-benchmark.json', report)
engine.close()
print(json.dumps(report))
